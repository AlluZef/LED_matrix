// Преобразование координат (x,y) в индекс в массиве leds
int getPixelIndex(int x, int y) {
    // Проверяем, находятся ли координаты в пределах матрицы
    if (x < 0 || x >= MATRIX_WIDTH || y < 0 || y >= MATRIX_HEIGHT) {
        return -1; // Возвращаем -1 для некорректных координат
    }
    
    // Для зигзагообразной матрицы с подключением LEFT_BOTTOM:
    // - Четные столбцы (0, 2, 4, ...) идут снизу вверх
    // - Нечетные столбцы (1, 3, 5, ...) идут сверху вниз
    if (x % 2 == 0) {
        // Четные столбцы: инвертируем Y
        return (MATRIX_HEIGHT - 1 - y) + x * MATRIX_HEIGHT;
    } else {
        // Нечетные столбцы: прямое отображение
        return y + x * MATRIX_HEIGHT;
    }
}

// Установка цвета пикселя по координатам (x,y)
void setPixel(int x, int y, CRGB color) {
    // Получаем индекс пикселя в массиве leds
    int index = getPixelIndex(x, y);
    
    // Проверяем, что индекс корректный
    if (index >= 0 && index < NUM_LEDS) {
        leds[index] = color; // Устанавливаем цвет
    }
}